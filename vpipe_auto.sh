#!/bin/bash
#set -ueo pipefail

# ==============================================================================
# V-pipe Automated Pipeline: Alignment, Variant Calling, Annotation, & Dashboard
# Usage: ./vpipe_auto.sh [AF_THRESHOLD] (Default: 0.01)
# ==============================================================================

# 1. Configuration & Parameters
MIN_AF=${1:-0.01}
MIN_DP=100
REF_FASTA="references/reference.fasta"
REF_GFF="references/reference.gff3"

# Dynamically extract REFERENCE_ID from FASTA header (e.g., >IAV_H5N1_PB2 -> IAV_H5N1)
if [ -f "$REF_FASTA" ]; then
    REFERENCE_ID=$(grep ">" "$REF_FASTA" | head -n 1 | cut -d'_' -f1,2 | sed 's/^>//')
else
    REFERENCE_ID="Unknown_Virus"
fi

# Extract snv_caller from config.yaml
SNV_CALLER=$(awk '/^[[:space:]]*snv_caller:/ {print tolower($2)}' config.yaml 2>/dev/null || echo "unknown")

SNPEFF_CONFIG="snpeff.config"
WORKING_DIR=$(pwd)

echo "--- Starting Pipeline Analysis for $REFERENCE_ID ---"
echo "Threshold: AF > $MIN_AF, DP > $MIN_DP"
echo "SNV Caller: $SNV_CALLER"

# --- Step 1: Mapping and cleaning filenames in raw_data folders ---
echo "--- Step 1: Mapping and cleaning filenames in raw_data folders ---"
mkdir -p samples
for f in fa/*; do
    [ -e "$f" ] || continue
    filename=$(basename "$f")
    
    # Extract components from Illumina format
    sample_id=$(echo "$filename" | cut -d'_' -f1)
    s_tag=$(echo "$filename" | cut -d'_' -f2)
    
    # Identify if it is Read 1 or Read 2
    if [[ "$filename" =~ _R1[._] ]]; then
        read_pair="R1"
    elif [[ "$filename" =~ _R2[._] ]]; then
        read_pair="R2"
    else
        echo "Varning: Kunde inte identifiera R1/R2 för $filename. Hoppar över."
        continue
    fi
    
    # Construct the cleaned filename
    new_filename="${sample_id}_${s_tag}_${read_pair}.fastq.gz"
    
    # Create the required subfolder structure
    target_dir="$WORKING_DIR/samples/$sample_id/$s_tag/raw_data"
    mkdir -p "$target_dir"
    
    # Create symbolic link
    ln -sf "$WORKING_DIR/$f" "$target_dir/$new_filename"
    echo "  Mapped: $filename -> $new_filename"
done

# --- Step 2: SnpEff Environment Auto-Setup & Rebuild ---
echo "--- Step 2: Recreating SnpEff Configuration and Database ---"

cat <<EOF > "$SNPEFF_CONFIG"
# SnpEff configuration file (Auto-generated by vpipe_auto.sh)
data.dir = ./snpeff_db

# Definiera genomet baserat på variabeln REFERENCE_ID
$REFERENCE_ID.genome : $REFERENCE_ID
EOF

# Clear old database and prepare folders
rm -rf "snpeff_db/$REFERENCE_ID"
mkdir -p "snpeff_db/$REFERENCE_ID"

# Copy reference files
cp "$REF_FASTA" "snpeff_db/$REFERENCE_ID/sequences.fa"
cp "$REF_GFF" "snpeff_db/$REFERENCE_ID/genes.gff"

mkdir -p logs

# Rebuild the database
snpEff build -c "$SNPEFF_CONFIG" -gff3 -noCheckCds -noCheckProtein -v "$REFERENCE_ID" > logs/snpeff_build.log 2>&1
echo "  - SnpEff database rebuilt. Log: logs/snpeff_build.log"

# --- Step 3: Running V-pipe Core Workflow ---
echo "--- Step 3: Running V-pipe ---"
./vpipe --jobs 2 --cores 16 

# --- Step 4: Annotation & Quality Filtering ---
echo "--- Step 4: Annotation & Filtering ---"
find results -name "snvs.vcf" | while read -r vcf; do
    sample_dir=$(dirname "$vcf")
    sample_name=$(echo "$vcf" | cut -d'/' -f2)
    s_folder=$(echo "$vcf" | cut -d'/' -f3)
    
    sanitized_vcf="${vcf%.vcf}.sanitized.vcf"
    annotated_vcf="${vcf%.vcf}.annotated.vcf"
    final_vcf="${vcf%.vcf}.final.vcf"
    
    summary_html="$sample_dir/snpEff_summary.html"

    echo "Processing: $sample_name ($s_folder)"

    # 1. Config-Driven VCF Sanitization
    if [[ "$SNV_CALLER" == "shorah" ]]; then
        echo "  - ShoRAH configured: Sanitizing indels and converting read counts to DP/AF..."
	awk -F'\t' -v OFS='\t' '
        /^##INFO=/ { print; next }
        /^#CHROM/ {
            print "##INFO=<ID=DP,Number=1,Type=Integer,Description=\"Total Depth (Ftot+Rtot)\">"
            print "##INFO=<ID=AF,Number=1,Type=Float,Description=\"Allele Frequency ((Fvar+Rvar)/DP)\">"
            print; next
        }
        /^#/ { print; next }
        # SnpEff-säkring: Släpp endast igenom standardiserade rader utan bindestreck
        $4 != "-" && $5 != "-" {
            dp = 0; af = 0
            if (match($8, /Ftot=[0-9]+/)) {
                ftot = substr($8, RSTART+5, RLENGTH-5)
                match($8, /Rtot=[0-9]+/)
                rtot = substr($8, RSTART+5, RLENGTH-5)
                dp = ftot + rtot
            }
            if (match($8, /Fvar=[0-9]+/)) {
                fvar = substr($8, RSTART+5, RLENGTH-5)
                match($8, /Rvar=[0-9]+/)
                rvar = substr($8, RSTART+5, RLENGTH-5)
                if (dp > 0) af = (fvar + rvar) / dp
            }
            $8 = $8 ";DP=" dp ";AF=" af
            print
        }' "$vcf" > "$sanitized_vcf"
    else
        echo "  - Standard VCF caller ($SNV_CALLER) configured: Bypassing sanitization..."
        cp "$vcf" "$sanitized_vcf"
    fi

    # 2. Annotation using sanitized VCF
    snpEff -c "$SNPEFF_CONFIG" \
           -s "$summary_html" \
           "$REFERENCE_ID" "$sanitized_vcf" > "$annotated_vcf"

    # 3. Quality Filtering using bcftools
    bcftools filter -i "AF > $MIN_AF && DP > $MIN_DP" "$annotated_vcf" > "$final_vcf"
    count=$(awk '!/^#/{c++} END{print c+0}' "$final_vcf")
    echo "  - Result: $count high-confidence variants."
done

# --- Step 5: Generating Results Dashboard ---
echo "--- Step 5: Generating Dashboard ---"
DASHBOARD_FILE="results/dashboard.html"

cat <<EOF > "$DASHBOARD_FILE"
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>V-pipe Segment Dashboard</title>
    <style>
        body { font-family: sans-serif; margin: 0; display: flex; height: 100vh; background: #f8f9fa; }
        #sidebar { width: 350px; background: #2c3e50; color: white; overflow-y: auto; display: flex; flex-direction: column; }
        #sidebar h2 { padding: 20px; margin: 0; background: #1a252f; font-size: 1.1em; text-align: center; }
        .sample-link {
            padding: 12px 20px; border-bottom: 1px solid #34495e; cursor: pointer;
            display: flex; justify-content: space-between; align-items: center;
            text-decoration: none; color: #ecf0f1; font-size: 0.85em;
        }
        .sample-link:hover { background: #34495e; }
        .sample-link.active { background: #3498db; font-weight: bold; }
        .badge { background: #e67e22; padding: 2px 7px; border-radius: 8px; font-size: 0.8em; font-weight: bold; }
        #viewer { flex-grow: 1; display: flex; flex-direction: column; }
        iframe { width: 100%; height: 100%; border: none; background: white; }
        .msg { padding: 50px; text-align: center; color: #7f8c8d; }
    </style>
</head>
<body>
    <div id="sidebar">
        <h2>🔬 Segment Analysis</h2>
        <div id="menu">
EOF

find results -name "snvs.final.vcf" | sort | while read -r vcf_path; do
    s_id=$(echo "$vcf_path" | cut -d'/' -f2)
    s_t=$(echo "$vcf_path" | cut -d'/' -f3)
    rel_html="${s_id}/${s_t}/visualization/snv_calling.html"
    v_count=$(awk '!/^#/{c++} END{print c+0}' "$vcf_path")
    echo "            <a class=\"sample-link\" onclick=\"load(this, '$rel_html')\">
                <span>$s_id ($s_t)</span>
                <span class=\"badge\">$v_count var</span>
            </a>" >> "$DASHBOARD_FILE"
done

cat <<EOF >> "$DASHBOARD_FILE"
        </div>
    </div>
    <div id="viewer">
        <div id="welcome" class="msg">
            <h2>Workflow Complete</h2>
            <p>Select a sample to view the interactive SNV plot.</p>
        </div>
        <iframe id="frame" src="about:blank"></iframe>
    </div>
    <script>
        function load(el, path) {
            document.getElementById('welcome').style.display = 'none';
            document.getElementById('frame').src = path;
            document.querySelectorAll('.sample-link').forEach(l => l.classList.remove('active'));
            el.classList.add('active');
        }
    </script>
</body>
</html>
EOF
